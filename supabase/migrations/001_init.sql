-- AFTERDARK - CREATION DE LA BASE DE DONNEES
-- ==========================================

-- 1. TABLE CATEGORIES
CREATE TABLE public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  icon VARCHAR(50),
  color VARCHAR(7)
);

-- 2. TABLE SPOTS
CREATE TABLE public.spots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  category_id BIGINT NOT NULL
    REFERENCES public.categories(id),
  description TEXT,
  images TEXT[] NOT NULL DEFAULT '{}',
  available BOOLEAN NOT NULL DEFAULT TRUE
);

-- 3. TABLE SPOT_INFOS
CREATE TABLE public.spot_infos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spot_id BIGINT NOT NULL UNIQUE
    REFERENCES public.spots(id) ON DELETE CASCADE,
  address TEXT,
  city VARCHAR(100) NOT NULL,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,

  CONSTRAINT valid_latitude
    CHECK (latitude BETWEEN -90 AND 90),
  CONSTRAINT valid_longitude
    CHECK (longitude BETWEEN -180 AND 180)
);

-- INDEX POUR LES FILTRES ET LES RECHERCHES
CREATE INDEX idx_spots_category
  ON public.spots(category_id);

CREATE INDEX idx_spot_infos_city
  ON public.spot_infos(city);

-- ACTIVER ROW LEVEL SECURITY
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.spots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.spot_infos ENABLE ROW LEVEL SECURITY;
